import type { CityData } from '../types/podatlas';
import { formatTime } from './format';

function escapeXml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

export function buildTripItineraryText(city: CityData): string {
  const lines = [
    `PODATLAS TRIP PACK — ${city.name.toUpperCase()}, ${city.country.toUpperCase()}`,
    '============================================================',
    city.tagline,
    '',
    'EPISODES TO QUEUE FOR YOUR FLIGHT:',
    ...city.episodes.map(
      (ep) =>
        `- [${formatTime(ep.durationSec)}] ${ep.show}: ${ep.title}${ep.audioUrl ? ` (${ep.audioUrl})` : ''}`
    ),
    '',
    'BOOKS MENTIONED:',
    ...city.books.map(
      (b) =>
        `- ${b.title} by ${b.author} (${b.show} @ ${formatTime(b.timestampSec)})${b.quote ? ` — "${b.quote}"` : ''}`
    ),
    '',
    'PLACES & TRAVEL GEAR MENTIONED:',
    ...city.placesAndGear.map(
      (p) => `- [${p.type}] ${p.name} (@ ${formatTime(p.timestampSec)}): ${p.note}`
    ),
    '',
    'Generated by PodAtlas — Podcast World Map & Recommendations',
  ];
  return lines.join('\n');
}

export function buildCityOpml(city: CityData): string {
  const uniqueShows = Array.from(new Set(city.episodes.map((ep) => ep.show)));
  const outlines = uniqueShows
    .map(
      (show) =>
        `      <outline type="rss" text="${escapeXml(show)}" title="${escapeXml(show)}" />`
    )
    .join('\n');

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<opml version="2.0">',
    '  <head>',
    `    <title>PodAtlas Trip Playlist — ${escapeXml(city.name)}, ${escapeXml(city.country)}</title>`,
    '  </head>',
    '  <body>',
    `    <outline text="${escapeXml(city.name)} Podcasts" title="${escapeXml(city.name)} Podcasts">`,
    outlines,
    '    </outline>',
    '  </body>',
    '</opml>',
    '',
  ].join('\n');
}

export function triggerFileDownload(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  anchor.click();
  URL.revokeObjectURL(url);
}
