import type { CityData } from '../types/podatlas';
import { formatTime } from './format';

function escapeXml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

export function buildTripItineraryText(city: CityData): string {
  const lines = [
    `PODATLAS TRIP PACK — ${city.name.toUpperCase()}, ${city.country.toUpperCase()}`,
    '============================================================',
    city.tagline,
    '',
    'EPISODES TO QUEUE FOR YOUR FLIGHT:',
    ...city.episodes.map(
      (ep) =>
        `- [${formatTime(ep.durationSec)}] ${ep.show}: ${ep.title}${ep.source === 'nps' ? ' [NPS Audio]' : ''}${ep.audioUrl ? ` (${ep.audioUrl})` : ''}`
    ),
    '',
    'BOOKS MENTIONED:',
    ...city.books.map((b) => {
      if (b.source === 'wikidata') {
        return `- ${b.title} by ${b.author} [Set in ${city.name}]${b.quote ? ` — "${b.quote}"` : ''}`;
      }
      const consensus =
        (b.uniqueShowCount ?? 1) >= 2 ? ` [★ ${b.uniqueShowCount} shows agree]` : '';
      const sourceSuffix =
        b.episodeId && b.show
          ? ` (${b.show} @ ${formatTime(b.timestampSec)})`
          : b.episodeId
            ? ` (@ ${formatTime(b.timestampSec)})`
            : b.show
              ? ` (${b.show})`
              : '';
      return `- ${b.title} by ${b.author}${consensus}${sourceSuffix}${b.quote ? ` — "${b.quote}"` : ''}`;
    }),
    '',
    'PLACES & TRAVEL GEAR MENTIONED:',
    ...city.placesAndGear.map((p) => {
      const unesco = p.isUnesco ? ' [UNESCO World Heritage]' : '';
      const consensus =
        (p.uniqueShowCount ?? 1) >= 2 ? ` [★ ${p.uniqueShowCount} shows]` : '';
      const coords = p.lat != null && p.lon != null ? ` (${p.lat.toFixed(4)}, ${p.lon.toFixed(4)})` : '';
      const timeSuffix = p.episodeId ? ` (@ ${formatTime(p.timestampSec)})` : '';
      return `- [${p.type}]${unesco} ${p.name}${consensus}${coords}${timeSuffix}: ${p.note}`;
    }),
    '',
    'Generated by PodAtlas — Podcast World Map & Recommendations',
  ];
  return lines.join('\n');
}

export function buildCityRssFeed(
  city: CityData,
  siteBaseUrl = 'https://podatlas.app'
): string {
  const cleanBase = siteBaseUrl.replace(/\/+$/, '');
  const cityUrl = `${cleanBase}/city/${city.id}`;
  const feedUrl = `${cleanBase}/feeds/${city.id}.xml`;

  const items = city.episodes
    .map((ep) => {
      const mentionLines = ep.mentions.map(
        (m) => `• [${formatTime(m.sec)}] ${m.label} (${m.type})`
      );
      const desc =
        mentionLines.length > 0
          ? `${ep.show}: ${ep.summary}\n\nMentioned:\n${mentionLines.join('\n')}`
          : `${ep.show}: ${ep.summary}`;
      const pubDate = new Date(ep.publishedAt).toUTCString();
      const validPubDate = pubDate === 'Invalid Date' ? new Date('2026-01-01T00:00:00Z').toUTCString() : pubDate;
      const lines = [
        '    <item>',
        `      <title>${escapeXml(`${ep.show} — ${ep.title}`)}</title>`,
        `      <guid isPermaLink="false">podatlas:${escapeXml(city.id)}:${escapeXml(ep.id)}</guid>`,
        `      <link>${escapeXml(cityUrl)}</link>`,
        `      <pubDate>${escapeXml(validPubDate)}</pubDate>`,
        `      <description>${escapeXml(desc)}</description>`,
        `      <itunes:author>${escapeXml(ep.show)}</itunes:author>`,
        `      <itunes:duration>${Math.max(0, Math.floor(ep.durationSec))}</itunes:duration>`,
        `      <itunes:summary>${escapeXml(ep.summary)}</itunes:summary>`,
      ];
      if (ep.audioUrl) {
        lines.push(`      <enclosure url="${escapeXml(ep.audioUrl)}" length="0" type="audio/mpeg" />`);
      }
      lines.push('    </item>');
      return lines.join('\n');
    })
    .join('\n');

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<rss version="2.0" xmlns:itunes="http://www.itunes.com/dtds/podcast-1.0.dtd" xmlns:atom="http://www.w3.org/2005/Atom">',
    '  <channel>',
    `    <title>PodAtlas: ${escapeXml(city.name)}, ${escapeXml(city.country)} Podcast Playlist</title>`,
    `    <link>${escapeXml(cityUrl)}</link>`,
    `    <atom:link href="${escapeXml(feedUrl)}" rel="self" type="application/rss+xml" />`,
    `    <description>${escapeXml(city.tagline)}</description>`,
    '    <language>en-us</language>',
    '    <itunes:author>PodAtlas</itunes:author>',
    `    <itunes:summary>${escapeXml(city.tagline)}</itunes:summary>`,
    items,
    '  </channel>',
    '</rss>',
    '',
  ].join('\n');
}

export function buildCityKml(city: CityData): string {
  const placemarks = city.placesAndGear
    .filter((p) => p.type !== 'Gear' && p.lat != null && p.lon != null)
    .map((p) => {
      const unesco = p.isUnesco ? ' [UNESCO World Heritage]' : '';
      const consensus =
        (p.uniqueShowCount ?? 1) >= 2 ? `Recommended by ${p.uniqueShowCount} shows. ` : '';
      const showSuffix =
        p.episodeId && p.show
          ? ` (${p.show} @ ${formatTime(p.timestampSec)})`
          : p.episodeId
            ? ` (@ ${formatTime(p.timestampSec)})`
            : p.show
              ? ` (${p.show})`
              : '';
      const desc = `[${p.type}]${unesco} ${consensus}${p.note}${showSuffix}`;
      return [
        '    <Placemark>',
        `      <name>${escapeXml(p.name)}</name>`,
        `      <description>${escapeXml(desc)}</description>`,
        '      <Point>',
        `        <coordinates>${p.lon},${p.lat},0</coordinates>`,
        '      </Point>',
        '    </Placemark>',
      ].join('\n');
    })
    .join('\n');

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<kml xmlns="http://www.opengis.net/kml/2.2">',
    '  <Document>',
    `    <name>PodAtlas Pins — ${escapeXml(city.name)}, ${escapeXml(city.country)}</name>`,
    `    <description>${escapeXml(city.tagline)}</description>`,
    placemarks,
    '  </Document>',
    '</kml>',
    '',
  ].join('\n');
}

export function buildCityOpml(city: CityData): string {
  const uniqueShows = Array.from(new Set(city.episodes.map((ep) => ep.show)));
  const outlines = uniqueShows
    .map(
      (show) =>
        `      <outline type="rss" text="${escapeXml(show)}" title="${escapeXml(show)}" />`
    )
    .join('\n');

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<opml version="2.0">',
    '  <head>',
    `    <title>PodAtlas Trip Playlist — ${escapeXml(city.name)}, ${escapeXml(city.country)}</title>`,
    '  </head>',
    '  <body>',
    `    <outline text="${escapeXml(city.name)} Podcasts" title="${escapeXml(city.name)} Podcasts">`,
    outlines,
    '    </outline>',
    '  </body>',
    '</opml>',
    '',
  ].join('\n');
}

export function triggerFileDownload(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  anchor.click();
  URL.revokeObjectURL(url);
}
